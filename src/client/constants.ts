// ============================================================================
// 画布 / 几何常量：与 640×360 播放变体强耦合，属于运行时几何，不作为配置。
// ----------------------------------------------------------------------------
// 职责：集中存放与素材画布绑定的固定数值（脚底线、命中区、拖拽阈值、缩放基准、
//       统一贴边边距），供 pet.ts 定位/命中/贴边/移动距离缩放共用，避免魔法数字散落。
// 与其他模块的关系：
//   - HIT_BOX / DRAG_THRESHOLD → pet.ts 命中层（hit 矩形定位、拖拽 vs 点击判定）
//   - PET_REF_WIDTH → pet.ts tryMove 移动距离缩放基准（小宠物挪小步、大宠物挪大步）
//   - EDGE_M_* / EDGE_PAD → pet.ts 贴边边界（edgeBounds 钳制、currentCenterX 无 DOM 回落）
//   - CANVAS_H / FEET_Y → pet.ts 脚底对齐 padding（bottomPad）
// 已知坑：
//   - 所有数值与 640×360 素材强耦合：改素材画布尺寸必须同步改这里；HIT_BOX 是 thumb
//     原始像素坐标，换算成舞台百分比发生在 pet.ts 渲染期（除以 640 / 360）
//   - EDGE_M_* 是全量 97 个动画透明包围盒扫描后的折中结论（见下），不是随手拍的：
//     贴边量改大改小会直接影响「钱袋满溢」这类满画布动画的边缘截断
// ============================================================================
/** thumb 画布高度 */
export const CANVAS_H = 360;
/** thumb 画布上「脚底」的 y 坐标（人物站在 y=330 线上） */
export const FEET_Y = 330;
/** 点击/拖拽命中矩形（thumb 640×360 像素坐标） */
export const HIT_BOX = { x0: 200, y0: 50, x1: 440, y1: 335 };
/**
 * 拖拽判定阈值（px）：pointerdown 后累计位移超过该值即判定为「拖拽」而非「点击」。
 * 判定发生在 pet.ts handlePointerMove；未越阈值的按压松手后按点击（handleClick）处理。
 * 取 5px 是为容纳手抖/微动，同时足够灵敏、不会吞掉短距离拖拽意图。
 */
export const DRAG_THRESHOLD = 5;
/** 移动距离缩放基准（px）：config.jsonc 的 moves.minDist/maxDist 是「基准宠物宽 462px」下的绝对像素，
 *  运行时乘以 实际size/基准 等比缩放 —— 任何缩放下，行进距离与人物自身大小成比例（小宠物挪小步、大宠物挪大步） */
export const PET_REF_WIDTH = 462;
// ---- 统一贴边边界（所有动画共用，避免按动画贴边时宽动画触发位置跳跃/闪烁）----
// 依据：全量 97 个动画的透明像素包围盒扫描（0.1s 采样并集）。典型动画左右空白 ≈31%；
// 唯一离群值「余额-钱袋满溢」左右空白仅 12.8% / 10.6%（硬币喷溅几乎占满画布）。
// 折中取 EDGE_M = 0.20：典型动画贴边到约 60px；钱袋满溢仅在贴边侧的硬币峰值帧截断约 23-33px。
// 上下取全动画最小空白（t=0.0889 / b=0.0278）：上下方向永不截断。
/** 统一贴边边距（画布比例）：舞台允许伸出屏幕的量。
 *  EDGE_M_L / EDGE_M_R = 0.20（左右：典型动画贴边留约 60px 空窗；钱袋满溢仅在硬币峰值帧截断约 23-33px）。
 *  EDGE_M_T = 0.0889 / EDGE_M_B = 0.0278（上下：取全动画最小空白，上下方向永不截断角色可见像素）。 */
export const EDGE_M_L = 0.2;
export const EDGE_M_R = 0.2;
export const EDGE_M_T = 0.0889;
export const EDGE_M_B = 0.0278;
/** 统一安全垫（px）：角色可见像素与屏幕边缘保持的最小距离 */
export const EDGE_PAD = 10;
